/// Glyph rows for `ch`. ASCII 32–126 from the table; otherwise replacement.
pub fn glyph(ch: u8) -> &'static [u8; 8] {
    if (FIRST..=LAST).contains(&ch) {
        &GLYPHS[(ch - FIRST) as usize]
    } else {
        &REPLACEMENT
    }
}

/// Pixel at (`col`, `row`) of `ch`. `col` 0 is leftmost (LSB of the row).
pub fn glyph_pixel(ch: u8, col: u8, row: u8) -> bool {
    if col >= FONT_W as u8 || row >= FONT_H as u8 {
        return false;
    }
    glyph(ch)[row as usize] & (1 << col) != 0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ascii_32_to_126_are_present() {
        assert_eq!(GLYPHS.len(), (LAST - FIRST + 1) as usize);
        for c in FIRST..=LAST {
            let g = glyph(c);
            assert_eq!(g.len(), 8);
        }
    }

    #[test]
    fn space_is_blank() {
        assert_eq!(glyph(b' '), &[0, 0, 0, 0, 0, 0, 0, 0]);
    }

    #[test]
    fn replacement_is_defined_and_not_blank() {
        assert_ne!(glyph(0), &[0, 0, 0, 0, 0, 0, 0, 0]);
        assert_eq!(glyph(0), &REPLACEMENT);
        assert_eq!(glyph(127), &REPLACEMENT);
        assert_eq!(glyph(255), &REPLACEMENT);
        assert_eq!(glyph(b'A'), glyph(b'A'));
        assert_ne!(glyph(b'A'), &REPLACEMENT);
    }

    #[test]
    fn lsb_is_leftmost() {
        // '/' top row 0x60 = bits 5 and 6. LSB-left → pixels on the right.
        assert!(!glyph_pixel(b'/', 0, 0));
        assert!(glyph_pixel(b'/', 5, 0));
        assert!(glyph_pixel(b'/', 6, 0));
        // bottom row 0x01 = bit 0 → leftmost pixel.
        assert!(glyph_pixel(b'/', 0, 6));
        assert!(!glyph_pixel(b'/', 7, 6));
        // 'A' top 0x0C = bits 2 and 3, near center.
        assert!(glyph_pixel(b'A', 2, 0));
        assert!(glyph_pixel(b'A', 3, 0));
        assert!(!glyph_pixel(b'A', 0, 0));
    }

    #[test]
    fn out_of_glyph_is_off() {
        assert!(!glyph_pixel(b'A', 8, 0));
        assert!(!glyph_pixel(b'A', 0, 8));
    }
}
